'use strict';
// Generate the SQL Editor installer from ordered, checksummed source migrations.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..'),dir=path.join(root,'supabase/migrations');
const files=fs.readdirSync(dir).filter(name=>/^\d{3}_.+\.sql$/.test(name)).sort();
const parts=[`-- Generated by node scripts/build-sql.cjs. Do not edit this bundle directly.
-- One transaction: existing classrooms are retained; completed migrations are skipped.
begin;
select pg_advisory_xact_lock(17430430);
create schema if not exists pi_helper;
revoke all on schema pi_helper from public,anon,authenticated;
create table if not exists pi_helper.schema_migrations (
 version integer primary key, name text not null, sha256 text not null,
 applied_at timestamptz not null default now()
);
alter table pi_helper.schema_migrations enable row level security;
revoke all on pi_helper.schema_migrations from public,anon,authenticated;
do $installer$
begin
 if exists(select 1 from pi_helper.schema_migrations where version>${files.length}) then
  raise exception 'Installer is older than this database; use the latest release.';
 end if;`];
for(const [index,name] of files.entries()){
 const version=Number(name.slice(0,3));if(version!==index+1)throw Error('Migration numbers must be contiguous');
 const source=fs.readFileSync(path.join(dir,name),'utf8');
 const checksum=crypto.createHash('sha256').update(source).digest('hex');
 const body=source.replace(/^begin;\s*$/gmi,'').replace(/^commit;\s*$/gmi,'');
 if(!/^begin;/mi.test(source)||!/^commit;/mi.test(source))throw Error('Expected explicit transaction in '+name);
 parts.push(`
 if exists(select 1 from pi_helper.schema_migrations where version=${version} and (sha256<>'${checksum}' or name<>'${name}')) then
  raise exception 'Migration ${name} differs from the applied version; append a new migration instead.';
 end if;
 if not exists(select 1 from pi_helper.schema_migrations where version=${version}) then
  if exists(select 1 from pi_helper.schema_migrations where version>${version}) then
   raise exception 'Migration history has a gap at ${name}.';
  end if;
  execute $migration_${version}$${body}$migration_${version}$;
  insert into pi_helper.schema_migrations(version,name,sha256) values(${version},'${name}','${checksum}');
 end if;`);
}
parts.push('end;\n$installer$;\ncommit;\n');
const output=parts.join('\n'),target=path.join(root,'supabase/install.sql');
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output){console.error('SQL bundle is stale. Run node scripts/build-sql.cjs');process.exit(1)}
 console.log('SQL installer matches all '+files.length+' ordered sources.');
}else{fs.writeFileSync(target,output);console.log('Generated installer with '+files.length+' migrations.');}
